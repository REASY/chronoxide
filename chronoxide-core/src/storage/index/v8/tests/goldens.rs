pub(super) fn bytes(literal: &str) -> Vec<u8> {
    assert_eq!(literal.len() % 2, 0, "hex fixture has an odd length");
    literal
        .as_bytes()
        .chunks_exact(2)
        .map(|pair| (nibble(pair[0]) << 4) | nibble(pair[1]))
        .collect()
}

pub(super) fn assert_hex(actual: &[u8], expected: &str) {
    assert_eq!(actual, bytes(expected));
}

pub(super) fn assert_sha256(actual: &[u8], expected: &str) {
    assert_hex(Sha256::digest(actual).as_slice(), expected);
}

fn nibble(byte: u8) -> u8 {
    match byte {
        b'0'..=b'9' => byte - b'0',
        b'a'..=b'f' => byte - b'a' + 10,
        _ => panic!("invalid lowercase hex fixture"),
    }
}
